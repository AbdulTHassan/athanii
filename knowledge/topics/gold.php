    <h2 class="text-2xl font-bold text-gray-800 mb-4">
        Zakat on Gold & Silver
    </h2>

    <p class="text-gray-600 mb-6 leading-relaxed">
        Gold and silver are the two primary forms of wealth mentioned in 
        the Qur'an. Zakat on them is <strong>2.5% (1/40th)</strong> when 
        they reach the Nisab threshold and are held for a full lunar year.
    </p>

    <!-- QURAN VERSE -->
    <div class="my-6 p-6 bg-green-50 border-l-4 border-green-600 rounded-lg">
