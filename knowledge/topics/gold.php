        </p>
        <p class="text-center text-sm text-green-700 italic">
            "And those who hoard gold and silver and do not spend them in the way of Allah — 
            announce to them a painful torment."
        </p>
        <p class="text-center text-xs text-gray-500 mt-2">— Qur'an 9:34</p>
    </div>

