    <!-- KEY POINTS -->
    <div class="my-8 p-6 bg-blue-50 rounded-lg border border-blue-100">
        <h3 class="text-lg font-bold text-blue-900 mb-4 flex items-center gap-2">
            📌 Key Points
        </h3>
        <ul class="space-y-2 text-gray-700">
            <li class="flex items-start gap-2">
                <span class="text-green-600 mt-1">✅</span>
                <span>Zakat is due on gold and silver in <strong>any form</strong> — coins, bars, jewelry (if stored as wealth), etc.</span>
            </li>
            <li class="flex items-start gap-2">
                <span class="text-green-600 mt-1">✅</span>
                <span>If the quantity is below Nisab, <strong>no Zakat</strong> is due.</span>
            </li>
            <li class="flex items-start gap-2">
                <span class="text-green-600 mt-1">✅</span>
                <span>Gold and silver are <strong>combined</strong> if each alone is below Nisab.</span>
            </li>
            <li class="flex items-start gap-2">
                <span class="text-green-600 mt-1">✅</span>
                <span>Jewelry used for <strong>personal adornment</strong> is not subject to Zakat according to many scholars.</span>
            </li>
            <li class="flex items-start gap-2">
                <span class="text-green-600 mt-1">✅</span>
                <span>Jewelry stored as <strong>investment</strong> or <strong>savings</strong> is subject to Zakat.</span>
            </li>
        </ul>
    </div>

