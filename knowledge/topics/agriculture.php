    <h2 class="text-2xl font-bold text-gray-800 mb-4">
        Zakat on Agriculture
    </h2>

    <p class="text-gray-600 mb-6 leading-relaxed">
        Zakat is due on agricultural produce that is <strong>stored as food</strong> 
        (grains and dried fruits), when the harvest reaches the Nisab threshold 
        of <strong>5 Awsug</strong> (approximately 653 kg).
    </p>

    <!-- WHAT IS INCLUDED -->
    <div class="my-8 p-6 bg-lime-50 rounded-lg border border-lime-100">
