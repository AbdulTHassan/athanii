        </h3>
        <div class="grid md:grid-cols-2 gap-4">
            <div>
                <p class="font-semibold text-gray-800 mb-2">✅ Grains:</p>
                <ul class="text-sm text-gray-700 space-y-1 ml-4">
                    <li>• Wheat</li>
                    <li>• Barley</li>
                    <li>• Rice</li>
                    <li>• Corn / Maize</li>
                    <li>• Millet</li>
                    <li>• Beans, chickpeas, lentils</li>
                </ul>
            </div>
            <div>
                <p class="font-semibold text-gray-800 mb-2">✅ Fruits:</p>
                <ul class="text-sm text-gray-700 space-y-1 ml-4">
                    <li>• Dried dates</li>
                    <li>• Raisins</li>
                    <li>• Olives</li>
                </ul>
                <p class="font-semibold text-gray-800 mt-4 mb-2">❌ Not Included:</p>
                <ul class="text-sm text-gray-500 space-y-1 ml-4">
                    <li>• Vegetables</li>
                    <li>• Fresh fruits (non-dried)</li>
                </ul>
            </div>
