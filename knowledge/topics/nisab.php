    <!-- HAWL -->
    <h3 class="text-xl font-bold text-gray-800 mt-8 mb-4">
        Hawl (The Lunar Year)
    </h3>
    <p class="text-gray-600 mb-4 leading-relaxed">
        Zakat is only due when the wealth has been held for a full 
        <strong>lunar year (Hawl)</strong>. If the wealth drops below 
        the Nisab at any point during the year, the Hawl resets.
    </p>

    <div class="my-6 p-5 bg-gray-50 rounded-lg border">
        <h4 class="font-bold text-gray-800 mb-3">📅 Conditions for Hawl:</h4>
        <ul class="space-y-2 text-gray-700 text-sm">
            <li class="flex items-start gap-2">
                <span class="text-green-600 mt-1">✔</span>
                <span>Wealth must be <strong>above Nisab</strong> at the beginning and end of the year.</span>
            </li>
            <li class="flex items-start gap-2">
                <span class="text-green-600 mt-1">✔</span>
                <span>If wealth drops below Nisab mid-year, the Hawl <strong>restarts</strong>.</span>
            </li>
            <li class="flex items-start gap-2">
                <span class="text-green-600 mt-1">✔</span>
                <span>New wealth acquired during the year is added and its Hawl is counted with the original.</span>
            </li>
        </ul>
    </div>

    <!-- COMBINING GOLD AND SILVER -->
    <h3 class="text-xl font-bold text-gray-800 mt-8 mb-4">
        Combining Gold and Silver
    </h3>
    <p class="text-gray-600 mb-4 leading-relaxed">
        If a person owns gold that does not reach Nisab on its own, 
        and silver that does not reach Nisab on its own, the values 
        of both are <strong>combined</strong> to determine if Nisab 
        is reached.
    </p>

    <div class="my-6 p-4 bg-green-50 rounded-lg border-l-4 border-green-600">
        <p class="text-sm text-green-800">
            <strong>Example:</strong> If someone owns 50g of gold 
            (below 85g) and 400g of silver (below 595g), the 
            <em>total value</em> of both is calculated. If the total 
            exceeds the Nisab of silver, Zakat is due on both.
        </p>
