        <strong>Nisab</strong> is the minimum amount of wealth that a 
        Muslim must possess before Zakat becomes obligatory. If wealth 
        is below the Nisab, no Zakat is due. Nisab is measured in 
        <strong>gold</strong> or <strong>silver</strong>, and the 
        <em>lower</em> of the two is used to benefit the poor.
    </p>

