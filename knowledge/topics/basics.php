<div class="prose max-w-none">

    <!-- INTRO -->
    <h2 class="text-2xl font-bold text-gray-800 mb-4">
        What is Zakat?
    </h2>

    <p class="text-gray-600 mb-6 leading-relaxed">
        Zakat is one of the five pillars of Islam. It is a mandatory 
        charitable contribution that Allah has obligated upon every 
        Muslim who possesses a minimum amount of wealth (Nisab), 
        according to specific conditions. The word <em>Zakat</em> 
        linguistically means <strong>"purification"</strong> and 
        <strong>"growth"</strong> — it purifies wealth and the soul.
    </p>

    <!-- QURAN VERSE -->
    <div class="my-6 p-6 bg-green-50 border-l-4 border-green-600 rounded-lg">
        <p class="text-center text-lg text-green-800 mb-2 font-arabic" dir="rtl">
            خُذْ مِنْ أَمْوَالِهِمْ صَدَقَةً تُطَهِّرُهُمْ وَتُزَكِّيهِم بِهَا
        </p>
        <p class="text-center text-sm text-green-700 italic">
            "Take from their wealth a charity by which you purify them and cause them increase."
        </p>
        <p class="text-center text-xs text-gray-500 mt-2">— Qur'an 9:103</p>
    </div>

    <!-- KEY POINTS -->
    <div class="my-8 p-6 bg-blue-50 rounded-lg border border-blue-100">
        <h3 class="text-lg font-bold text-blue-900 mb-4 flex items-center gap-2">
            📌 Key Points About Zakat
        </h3>
        <ul class="space-y-2 text-gray-700">
            <li class="flex items-start gap-2">
                <span class="text-green-600 mt-1">✅</span>
                <span>It is the <strong>third pillar</strong> of Islam, mentioned alongside Salah in over 80 verses of the Qur'an.</span>
            </li>
            <li class="flex items-start gap-2">
                <span class="text-green-600 mt-1">✅</span>
                <span>The standard rate on wealth is <strong>2.5% (1/40th)</strong> after one lunar year (Hawl).</span>
            </li>
            <li class="flex items-start gap-2">
                <span class="text-green-600 mt-1">✅</span>
                <span>It is due on <strong>specific categories</strong> of wealth: gold, silver, cash, business assets, livestock, and agricultural produce.</span>
            </li>
            <li class="flex items-start gap-2">
                <span class="text-green-600 mt-1">✅</span>
                <span>Zakat must be given to the <strong>eight categories</strong> of recipients mentioned in the Qur'an (9:60).</span>
            </li>
            <li class="flex items-start gap-2">
                <span class="text-green-600 mt-1">✅</span>
                <span>It is different from <em>Sadaqah</em> (voluntary charity) — Zakat is <strong>obligatory</strong>, while Sadaqah is optional.</span>
            </li>
        </ul>
    </div>

    <!-- WISDOM OF ZAKAT -->
    <h3 class="text-xl font-bold text-gray-800 mt-8 mb-4">
        The Wisdom of Zakat
    </h3>
    <p class="text-gray-600 mb-4 leading-relaxed">
        Allah prescribed Zakat for profound reasons that benefit both 
        the individual and the community:
    </p>
    <ol class="list-decimal list-inside space-y-2 text-gray-700 mb-6">
        <li><strong>Purification of the soul</strong> from stinginess, greed, and love of wealth.</li>
        <li><strong>Comforting the poor</strong> and fulfilling the needs of the needy and deprived.</li>
        <li><strong>Establishing a balanced society</strong> where wealth circulates fairly.</li>
        <li><strong>Preventing wealth hoarding</strong> among the rich, keeping it accessible to all.</li>
    </ol>

    <!-- WHO MUST PAY -->
    <h3 class="text-xl font-bold text-gray-800 mt-8 mb-4">
        Who Must Pay Zakat?
    </h3>
    <p class="text-gray-600 mb-4 leading-relaxed">
        Zakat is obligatory upon every Muslim who meets the following 
        conditions:
    </p>
    <div class="grid md:grid-cols-2 gap-4 mb-6">
        <div class="p-4 bg-gray-50 rounded-lg border">
            <p class="font-semibold text-green-700 mb-1">1. Islam</p>
            <p class="text-sm text-gray-600">A non-Muslim is not required to pay Zakat.</p>
        </div>
        <div class="p-4 bg-gray-50 rounded-lg border">
            <p class="font-semibold text-green-700 mb-1">2. Freedom</p>
            <p class="text-sm text-gray-600">A free person (not enslaved).</p>
        </div>
        <div class="p-4 bg-gray-50 rounded-lg border">
            <p class="font-semibold text-green-700 mb-1">3. Maturity</p>
            <p class="text-sm text-gray-600">Reached the age of puberty (Baligh).</p>
        </div>
        <div class="p-4 bg-gray-50 rounded-lg border">
            <p class="font-semibold text-green-700 mb-1">4. Sound Mind</p>
            <p class="text-sm text-gray-600">Of sound mind ('Aqil).</p>
        </div>
        <div class="p-4 bg-gray-50 rounded-lg border md:col-span-2">
            <p class="font-semibold text-green-700 mb-1">5. Ownership of Nisab</p>
            <p class="text-sm text-gray-600">
                Must own wealth equal to or above the Nisab threshold 
                for a complete lunar year (Hawl).
            </p>
        </div>
    </div>

    <!-- WARNING -->
    <div class="my-8 p-4 bg-red-50 border-l-4 border-red-500 rounded-lg">
