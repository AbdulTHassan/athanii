    <h2 class="text-2xl font-bold text-gray-800 mb-4">
        Zakat-ul-Fitr
    </h2>

    <p class="text-gray-600 mb-6 leading-relaxed">
        <strong>Zakat-ul-Fitr</strong> is a special charity given at the end 
        of Ramadan by every Muslim who has enough food for themselves and 
        their dependents. It purifies the fasting person and provides food 
        for the poor on the day of Eid.
    </p>

    <!-- HADITH -->
    <div class="my-6 p-6 bg-green-50 border-l-4 border-green-600 rounded-lg">
        <p class="text-sm text-green-800 italic">
            "The Messenger of Allah ﷺ made Zakat-ul-Fitr obligatory as a purification 
            for the fasting person from useless and obscene speech, and as a means 
            of feeding the poor."
        </p>
        <p class="text-xs text-gray-500 mt-2 text-center">— Abu Dawud, Ibn Majah</p>
    </div>

    <!-- KEY POINTS -->
    <div class="my-8 p-6 bg-blue-50 rounded-lg border border-blue-100">
        <h3 class="text-lg font-bold text-blue-900 mb-4 flex items-center gap-2">
            📌 Key Points
        </h3>
        <ul class="space-y-2 text-gray-700">
            <li class="flex items-start gap-2">
                <span class="text-green-600 mt-1">✅</span>
                <span>Obligatory upon every Muslim — <strong>young and old, male and female, free and slave</strong>.</span>
            </li>
            <li class="flex items-start gap-2">
                <span class="text-green-600 mt-1">✅</span>
                <span>The head of the household pays on behalf of <strong>everyone he supports</strong>.</span>
            </li>
            <li class="flex items-start gap-2">
                <span class="text-green-600 mt-1">✅</span>
                <span>Amount: <strong>1 Sa'</strong> (approximately 2.5 kg) of the staple food of the land.</span>
            </li>
            <li class="flex items-start gap-2">
                <span class="text-green-600 mt-1">✅</span>
                <span>Common foods: wheat, barley, dates, rice, raisins, cheese.</span>
            </li>
            <li class="flex items-start gap-2">
                <span class="text-green-600 mt-1">✅</span>
                <span>Time: Must be given <strong>before the Eid prayer</strong>. It can be given 1-2 days before Eid.</span>
            </li>
        </ul>
    </div>

