                <span class="text-green-600 mt-1">✅</span>
                <span>Digital wallets (Paystack, Flutterwave, OPay, etc.)</span>
            </li>
            <li class="flex items-start gap-2">
                <span class="text-green-600 mt-1">✅</span>
                <span>Money owed to you that you expect to receive (good debts)</span>
