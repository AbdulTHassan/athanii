<div class="prose max-w-none">

    <h2 class="text-2xl font-bold text-gray-800 mb-4">
        The Recipients of Zakat
    </h2>

    <p class="text-gray-600 mb-6 leading-relaxed">
        Allah has specified <strong>eight categories</strong> of people who are 
        eligible to receive Zakat. These are mentioned in the Qur'an (9:60), and 
        no one outside these categories should receive Zakat.
    </p>

    <!-- QURAN VERSE -->
    <div class="my-6 p-6 bg-green-50 border-l-4 border-green-600 rounded-lg">
        <p class="text-center text-sm text-green-800 mb-2 font-arabic" dir="rtl">
            إِنَّمَا الصَّدَقَاتُ لِلْفُقَرَاءِ وَالْمَسَاكِينِ وَالْعَامِلِينَ عَلَيْهَا وَالْمُؤَلَّفَةِ قُلُوبُهُمْ 
            وَفِي الرِّقَابِ وَالْغَارِمِينَ وَفِي سَبِيلِ اللَّهِ وَابْنِ السَّبِيلِ
        </p>
        <p class="text-center text-sm text-green-700 italic">
            "Zakat is only for the poor, the needy, those employed to collect it, 
            those whose hearts are to be reconciled, to free captives, 
            those in debt, in the cause of Allah, and the wayfarer."
        </p>
        <p class="text-center text-xs text-gray-500 mt-2">— Qur'an 9:60</p>
    </div>

    <!-- THE 8 CATEGORIES -->
    <h3 class="text-xl font-bold text-gray-800 mt-8 mb-4">
        The Eight Categories
    </h3>

    <div class="space-y-4">

        <!-- 1. AL-FUQARA -->
        <div class="p-5 bg-white border-l-4 border-green-600 rounded-lg shadow-sm">
            <div class="flex items-start gap-3">
                <div class="flex-shrink-0 w-10 h-10 rounded-full bg-green-100 text-green-700 flex items-center justify-center font-bold">1</div>
                <div>
                    <h4 class="font-bold text-gray-800 mb-1">Al-Fuqara (The Poor)</h4>
                    <p class="text-sm text-gray-600">
                        Those who do not have enough wealth to meet their basic needs 
                        (food, clothing, housing) and the needs of their dependents.
                    </p>
                </div>
            </div>
        </div>

        <!-- 2. AL-MASAKIN -->
        <div class="p-5 bg-white border-l-4 border-green-600 rounded-lg shadow-sm">
            <div class="flex items-start gap-3">
                <div class="flex-shrink-0 w-10 h-10 rounded-full bg-green-100 text-green-700 flex items-center justify-center font-bold">2</div>
                <div>
                    <h4 class="font-bold text-gray-800 mb-1">Al-Masakin (The Needy)</h4>
                    <p class="text-sm text-gray-600">
                        Those who have some wealth but not enough to meet their needs. 
                        They do not beg and conceal their poverty.
                    </p>
                </div>
            </div>
        </div>

        <!-- 3. AL-AMILIN -->
        <div class="p-5 bg-white border-l-4 border-green-600 rounded-lg shadow-sm">
            <div class="flex items-start gap-3">
                <div class="flex-shrink-0 w-10 h-10 rounded-full bg-green-100 text-green-700 flex items-center justify-center font-bold">3</div>
                <div>
                    <h4 class="font-bold text-gray-800 mb-1">Al-'Amilin 'Alayha (Zakat Collectors)</h4>
                    <p class="text-sm text-gray-600">
                        Those appointed by the Muslim authority to collect, guard, 
                        and distribute Zakat. They are given a wage for their work.
                    </p>
                </div>
            </div>
        </div>

        <!-- 4. AL-MU'ALLAFAH -->
        <div class="p-5 bg-white border-l-4 border-green-600 rounded-lg shadow-sm">
            <div class="flex items-start gap-3">
                <div class="flex-shrink-0 w-10 h-10 rounded-full bg-green-100 text-green-700 flex items-center justify-center font-bold">4</div>
                <div>
                    <h4 class="font-bold text-gray-800 mb-1">Al-Mu'allafah Qulubuhum (Reconciled Hearts)</h4>
                    <p class="text-sm text-gray-600">
                        Those whose hearts are to be reconciled to Islam, or 
                        whose harm is to be prevented.
                    </p>
                </div>
            </div>
        </div>

        <!-- 5. AR-RIQAB -->
        <div class="p-5 bg-white border-l-4 border-green-600 rounded-lg shadow-sm">
            <div class="flex items-start gap-3">
                <div class="flex-shrink-0 w-10 h-10 rounded-full bg-green-100 text-green-700 flex items-center justify-center font-bold">5</div>
                <div>
                    <h4 class="font-bold text-gray-800 mb-1">Ar-Riqab (To Free Captives)</h4>
                    <p class="text-sm text-gray-600">
                        Used to free slaves, captives, or to help those in bondage.
                    </p>
                </div>
            </div>
        </div>

        <!-- 6. AL-GHARIMUN -->
        <div class="p-5 bg-white border-l-4 border-green-600 rounded-lg shadow-sm">
            <div class="flex items-start gap-3">
                <div class="flex-shrink-0 w-10 h-10 rounded-full bg-green-100 text-green-700 flex items-center justify-center font-bold">6</div>
                <div>
                    <h4 class="font-bold text-gray-800 mb-1">Al-Gharimun (Those in Debt)</h4>
                    <p class="text-sm text-gray-600">
                        Those who are burdened with debt that they cannot repay, 
                        provided the debt was not acquired through disobedience to Allah.
                    </p>
                </div>
            </div>
        </div>

        <!-- 7. FI SABILILLAH -->
        <div class="p-5 bg-white border-l-4 border-green-600 rounded-lg shadow-sm">
            <div class="flex items-start gap-3">
                <div class="flex-shrink-0 w-10 h-10 rounded-full bg-green-100 text-green-700 flex items-center justify-center font-bold">7</div>
                <div>
                    <h4 class="font-bold text-gray-800 mb-1">Fi Sabilillah (In the Way of Allah)</h4>
                    <p class="text-sm text-gray-600">
                        For the cause of Allah — primarily Jihad, and also includes 
                        building Masjids, schools, hospitals, and other beneficial causes.
                    </p>
                </div>
            </div>
        </div>

        <!-- 8. IBN AS-SABIL -->
        <div class="p-5 bg-white border-l-4 border-green-600 rounded-lg shadow-sm">
            <div class="flex items-start gap-3">
                <div class="flex-shrink-0 w-10 h-10 rounded-full bg-green-100 text-green-700 flex items-center justify-center font-bold">8</div>
                <div>
                    <h4 class="font-bold text-gray-800 mb-1">Ibn as-Sabil (The Wayfarer)</h4>
                    <p class="text-sm text-gray-600">
                        The traveler who is stranded and cut off from his wealth, 
                        even if he is wealthy in his own land.
                    </p>
                </div>
            </div>
        </div>

    </div>

    <!-- IMPORTANT NOTES -->
    <div class="my-8 p-6 bg-amber-50 border-l-4 border-amber-500 rounded-lg">
        <h3 class="font-bold text-amber-900 mb-3">📌 Important Notes</h3>
        <ul class="space-y-2 text-sm text-amber-800">
            <li>• Zakat is <strong>not</strong> given to the wealthy, nor to the strong who are able to earn.</li>
            <li>• Zakat is <strong>not</strong> given to parents, children, or spouse (their maintenance is obligatory upon you).</li>
            <li>• Zakat is <strong>not</strong> given to the family of the Prophet ﷺ (Banu Hashim).</li>
            <li>• It is permissible to give Zakat to one category, or distribute it among several.</li>
            <li>• Priority should be given to the <strong>most needy</strong> among the categories.</li>
        </ul>
    </div>

